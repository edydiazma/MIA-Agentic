-- 36 · Hub de integraciones (docs/data-model.md §21.3)
--
-- Conectores listos (Shopify, WooCommerce, VTEX, Google Calendar, Outlook, Zoho CRM, Odoo, BigQuery) y un
-- constructor de conectores genéricos (REST + mapeo) para DMS/ERP. Pedidos externos para atribución y journeys,
-- sincronización de citas con calendarios, y exportación de datos a un almacén (BigQuery / S3 / GCS).
