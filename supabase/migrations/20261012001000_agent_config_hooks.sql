-- Webhooks entrantes (sistemas externos: agenda de taller, DMS, ERP…) --------------------------------------------
create table public.inbound_webhooks (
  id               bigint generated by default as identity primary key,
  organization_id  bigint not null references public.organizations(id) on delete cascade,
  name             text not null,                -- "Confirmación Cita V.5"
  slug             text not null unique,         -- /hooks/{slug}
  token_hash       text not null,                -- sha256 del token (cabecera X-Hook-Token o ?token=)
  status           text not null default 'active' check (status in ('draft', 'active', 'paused')),
  action           text not null check (action in
                     ('send_template', 'send_text', 'start_flow', 'upsert_contact', 'create_deal', 'create_appointment')),
  channel_id       bigint references public.channels(id) on delete set null,
  template_name    text,
  template_language text,
  flow_id          bigint references public.flows(id) on delete set null,
  -- [{name, label, type(text|number|date|datetime|phone|email|url|currency), required, example,
  --   maps_to: "recipient.phone" | "recipient.bsuid" | "template.header.1" | "template.body.N" | "template.button.N" |
  --            "contact.name" | "field:<key>" | "key:<golden_type>" | "vehicle.<attr>" | "deal.<attr>" |
  --            "appointment.<attr>" | "flow.var.<name>"}]
  params           jsonb not null default '[]'::jsonb check (jsonb_typeof(params) = 'array'),
  -- {assign_group_id, assign_agent_id, bot: on|off, tags[], typification, pipeline, dedupe_minutes}
  options          jsonb not null default '{}'::jsonb,
  version          int not null default 1,
  executions       bigint not null default 0,
  succeeded        bigint not null default 0,
  failed           bigint not null default 0,
  last_run_at      timestamptz,
  created_by       bigint references public.agents(id) on delete set null,
  published_at     timestamptz,
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now(),
  unique (organization_id, name)
);
create trigger trg_inbound_webhooks_updated before update on public.inbound_webhooks
  for each row execute function public.set_updated_at();

create table public.inbound_webhook_runs (
  id               bigint generated by default as identity,
  organization_id  bigint not null,
  webhook_id       bigint not null,
  status           text not null check (status in ('succeeded', 'failed', 'rejected', 'duplicate')),
  http_status      smallint not null,
  payload          jsonb,                        -- parámetros recibidos (recortados)
  result           jsonb,                        -- ids creados / message_id
  contact_id       bigint,
  conversation_id  bigint,
  error            text,
  latency_ms       int,
  ip               text,
  idempotency_key  text,
  created_at       timestamptz not null default now(),
  primary key (id, created_at)
) partition by range (created_at);
create table public.inbound_webhook_runs_default partition of public.inbound_webhook_runs default;
select public.ensure_monthly_partitions('public.inbound_webhook_runs', 3);
create index inbound_webhook_runs_hook_idx on public.inbound_webhook_runs (webhook_id, created_at desc);
create index inbound_webhook_runs_idem_idx on public.inbound_webhook_runs (webhook_id, idempotency_key, created_at)
  where idempotency_key is not null;

-- Contadores (ejecuciones / exitosas / erróneas) mantenidos por la base
create or replace function private.trg_inbound_webhook_runs_counters() returns trigger
language plpgsql set search_path = public, pg_temp as $$
begin
  update public.inbound_webhooks set executions = executions + 1,
    succeeded = succeeded + (new.status = 'succeeded')::int,
    failed = failed + (new.status in ('failed', 'rejected'))::int,
    last_run_at = new.created_at
  where id = new.webhook_id;
  return null;
end $$;
revoke all on function private.trg_inbound_webhook_runs_counters() from public;
create trigger trg_inbound_webhook_runs_counters after insert on public.inbound_webhook_runs
  for each row execute function private.trg_inbound_webhook_runs_counters();

do $$
begin
  if exists (select 1 from pg_extension where extname = 'pg_cron') then
    perform cron.schedule('inbound-webhook-runs-partitions', '25 3 * * *', $c$
      select public.ensure_monthly_partitions('public.inbound_webhook_runs', 3);
      select public.drop_old_partitions('public.inbound_webhook_runs', 6);
    $c$);
  end if;
end $$;

