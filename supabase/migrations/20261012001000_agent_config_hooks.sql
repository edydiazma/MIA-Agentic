-- Agente de IA: contexto de pauta, optimización de costos, seguridad, recuperación, zona horaria ------------------
alter table public.ai_agents
  add column timezone                 text,              -- null = la de la empresa
  add column max_words                int check (max_words between 20 and 2000),
  -- Reconocimiento de pauta: el primer mensaje se personaliza con el anuncio / publicación / enlace de origen
  add column ad_context_enabled       boolean not null default true,
  add column ad_context_prompt        text,
  -- Reglas por fuente: [{match: {channel?, source_type?, ad_id?, campaign_contains?, link_id?, portal?: "mercadolibre"|
  --   "tucarro"|..., text_contains?}, actions: {group_id?, tags?[], stage?: {pipeline, key}, skip_intent_question?,
  --   handoff?: bool, note?}}]  (validado con JSON Schema en la app)
  add column source_rules             jsonb not null default '[]'::jsonb,
  -- Optimización de costos de WhatsApp: agrupa mensajes consecutivos, evita plantillas dentro de la ventana de servicio,
  -- recupera solo dentro de la ventana gratuita y prioriza la ventana de 72 h de Click to WhatsApp
  add column cost_optimization        boolean not null default true,
  -- Seguridad: detecta spam o intención maliciosa y termina la conversación
  add column security_enabled         boolean not null default true,
  add column security_prompt          text,
  add column security_action          text not null default 'close' check (security_action in ('close', 'block', 'handoff', 'flag')),
  -- Recuperación por inactividad: hasta 3 intentos [{after_hours (≤12), message (guía o texto), use_ai: bool}]
  add column recovery_enabled         boolean not null default false,
  add column recovery_attempts        jsonb not null default '[]'::jsonb
                                        check (jsonb_typeof(recovery_attempts) = 'array' and jsonb_array_length(recovery_attempts) <= 3),
  add column inactivity_end_hours     numeric(5, 2),     -- fin por inactividad (después del último intento)
  add column inactivity_end_typification_id bigint references public.typifications(id) on delete set null,
  -- Campos que este agente debe identificar (vacío = todos los contact_fields con ai_extract)
  add column extract_field_ids        bigint[] not null default '{}';

