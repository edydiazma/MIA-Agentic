-- Etapas por línea de negocio (Lead → MQL → SQL…) con condición para la IA ----------------------------------
create table public.pipeline_stages (
  id               bigint generated by default as identity primary key,
  organization_id  bigint not null references public.organizations(id) on delete cascade,
  pipeline         text not null,                -- nuevos | usados | taller | repuestos_accesorios | pqr | default…
  key              text not null check (key ~ '^[a-z][a-z0-9_]{0,49}$'),
  name             text not null,                -- "MQL (Marketing Qualified Lead)"
  external_name    text,                         -- nombre en el CRM / Atom
  ai_condition     text,                         -- cuándo la IA marca esta etapa (null = solo manual)
  position         int not null default 100,
  probability      smallint check (probability between 0 and 100),
  is_won           boolean not null default false,
  is_lost          boolean not null default false,
  is_active        boolean not null default true,
  created_at       timestamptz not null default now(),
  unique (organization_id, pipeline, key),
  check (not (is_won and is_lost))
);

create table public.deal_stage_events (
  id               bigint generated by default as identity primary key,
  organization_id  bigint not null references public.organizations(id) on delete cascade,
  deal_id          bigint not null references public.deals(id) on delete cascade,
  from_stage       text,
  to_stage         text not null,
  source           text not null check (source in ('ai', 'agent', 'flow', 'crm', 'api', 'rule', 'webhook')),
  reason           text,                         -- evidencia / condición cumplida
  confidence       real,
  agent_id         bigint references public.agents(id) on delete set null,
  conversation_id  bigint references public.conversations(id) on delete set null,
  created_at       timestamptz not null default now()
);
create index deal_stage_events_deal_idx on public.deal_stage_events (deal_id, created_at);
create index deal_stage_events_org_idx on public.deal_stage_events (organization_id, created_at);
alter table public.deals add column stage_changed_at timestamptz;

