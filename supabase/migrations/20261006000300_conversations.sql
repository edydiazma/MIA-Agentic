-- Eventos de etiquetas
create or replace function public.trg_conversation_tags_events() returns trigger
language plpgsql as $$
declare
  conv public.conversations;
  rec record := coalesce(new, old);
begin
  select * into conv from public.conversations where id = rec.conversation_id;
  if conv.id is not null then
    perform public.log_conversation_event(conv, case when tg_op = 'INSERT' then 'tagged' else 'untagged' end,
      jsonb_build_object('tag_id', rec.tag_id, 'source', rec.source));
  end if;
  return null;
end $$;

create trigger trg_conversation_tags_events after insert or delete on public.conversation_tags
  for each row execute function public.trg_conversation_tags_events();
