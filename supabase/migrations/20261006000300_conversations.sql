create or replace function public.log_conversation_event(
  p_conv public.conversations, p_type text, p_payload jsonb default null
) returns void
language sql as $$
  insert into public.conversation_events
    (organization_id, conversation_id, event_type, actor_type, actor_agent_id, assigned_agent_id, group_id, payload)
  values (p_conv.organization_id, p_conv.id, p_type, public.current_actor_type(), public.current_actor_agent_id(),
          p_conv.assigned_agent_id, p_conv.group_id, p_payload);
$$;

-- Los eventos de estado se generan en la base: ningún camino de escritura puede saltárselos
create or replace function public.trg_conversation_events() returns trigger
language plpgsql as $$
begin
  if tg_op = 'INSERT' then
    perform public.log_conversation_event(new, 'created');
    return new;
  end if;
  if new.status is distinct from old.status then
    if old.status = 'closed' then
      perform public.log_conversation_event(new, 'reopened', jsonb_build_object('to', new.status));
    elsif new.status = 'closed' then
      perform public.log_conversation_event(new, 'closed', jsonb_build_object(
        'typification_id', new.typification_id, 'had_handoff', new.handoff_at is not null));
    elsif old.status = 'bot' and new.status = 'human' then
      perform public.log_conversation_event(new, 'handoff', jsonb_build_object('reason', new.handoff_reason));
    elsif old.status = 'human' and new.status = 'bot' then
      perform public.log_conversation_event(new, 'released');
    end if;
  end if;
  if new.assigned_agent_id is distinct from old.assigned_agent_id then
    perform public.log_conversation_event(new, case when new.assigned_agent_id is null then 'unassigned' else 'assigned' end,
      jsonb_build_object('from', old.assigned_agent_id, 'to', new.assigned_agent_id));
  end if;
  if new.group_id is distinct from old.group_id then
    perform public.log_conversation_event(new, 'routed', jsonb_build_object('from', old.group_id, 'to', new.group_id));
  end if;
  if new.typification_id is distinct from old.typification_id and new.typification_id is not null then
    perform public.log_conversation_event(new, 'typified', jsonb_build_object('typification_id', new.typification_id));
  end if;
  if new.ai_classified_at is distinct from old.ai_classified_at then
    perform public.log_conversation_event(new, 'classified',
      jsonb_build_object('ai_typification_id', new.ai_typification_id, 'sentiment', new.ai_sentiment));
  end if;
  return new;
end $$;

create trigger trg_conversations_events after insert or update on public.conversations
  for each row execute function public.trg_conversation_events();

-- Reglas de negocio de la conversación al cambiar de estado
create or replace function public.trg_conversation_state() returns trigger
language plpgsql as $$
begin
  if new.status = 'closed' and old.status <> 'closed' then
    new.closed_at := coalesce(new.closed_at, now());
    new.unread_count := 0;
    update public.conversation_suggestions set status = 'expired'
      where conversation_id = new.id and status = 'pending';
  elsif old.status = 'closed' and new.status <> 'closed' then
    new.closed_at := null;
    new.typification_id := null;
    new.reopened_count := old.reopened_count + 1;
    new.handoff_at := null;
    new.first_response_at := null;
  end if;
  return new;
end $$;

create trigger trg_conversations_state before update of status on public.conversations
  for each row execute function public.trg_conversation_state();

-- Contadores y primera respuesta: se mantienen desde messages
create or replace function public.trg_messages_after_insert() returns trigger
language plpgsql as $$
declare
  conv public.conversations;
begin
  update public.conversations c set
    message_count = c.message_count + 1,
    inbound_count = c.inbound_count + (new.direction = 'in')::int,
    unread_count = c.unread_count + (new.direction = 'in')::int,
    last_message_at = greatest(c.last_message_at, new.created_at),
    last_inbound_at = case when new.direction = 'in' then new.created_at else c.last_inbound_at end,
    last_message_preview = case when new.sender_type = 'system' then c.last_message_preview else
      left(coalesce(new.text, new.transcript, '[' || new.type || ']'), 255) end,
    first_response_at = case
      when new.sender_type = 'agent' and c.handoff_at is not null and c.first_response_at is null
           and new.created_at >= c.handoff_at then new.created_at
      else c.first_response_at end
  where c.id = new.conversation_id
  returning c.* into conv;

  if new.sender_type = 'agent' and conv.first_response_at = new.created_at then
    perform public.log_conversation_event(conv, 'first_agent_response',
      jsonb_build_object('seconds', extract(epoch from new.created_at - conv.handoff_at)::int));
  end if;
  if new.wa_message_id is not null then
    insert into public.message_wa_ids (wa_message_id, organization_id, message_id, message_created_at, conversation_id)
    values (new.wa_message_id, new.organization_id, new.id, new.created_at, new.conversation_id)
    on conflict (wa_message_id) do nothing;
  end if;
  return null;
end $$;

create trigger trg_messages_after_insert after insert on public.messages
  for each row execute function public.trg_messages_after_insert();

