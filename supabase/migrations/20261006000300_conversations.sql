-- ---------------------------------------------------------------------------
-- Hechos de conversación (append-only, particionado): fuente del reporting
-- ---------------------------------------------------------------------------
create table public.conversation_events (
  id               bigint generated by default as identity,
  organization_id  bigint not null references public.organizations(id) on delete cascade,
  conversation_id  bigint not null references public.conversations(id) on delete cascade,
  event_type       text not null check (event_type in
                     ('created', 'reopened', 'handoff', 'released', 'assigned', 'unassigned', 'routed',
                      'first_agent_response', 'tagged', 'untagged', 'typified', 'classified', 'closed',
                      'flow_started', 'flow_finished', 'campaign_sent')),
  actor_type       text not null default 'system' check (actor_type in
                     ('system', 'bot', 'agent', 'ai', 'contact', 'automation', 'flow')),
  actor_agent_id   bigint,
  assigned_agent_id bigint,                     -- estado al momento del evento (para atribuir en reportes)
  group_id         bigint,
  payload          jsonb,
  occurred_at      timestamptz not null default now(),
  primary key (id, occurred_at)
) partition by range (occurred_at);

create table public.conversation_events_default partition of public.conversation_events default;
select public.ensure_monthly_partitions('public.conversation_events', 3);

create index conv_events_conv_idx on public.conversation_events (conversation_id, occurred_at);
create index conv_events_org_type_idx on public.conversation_events (organization_id, event_type, occurred_at);

