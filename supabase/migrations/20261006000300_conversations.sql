-- ---------------------------------------------------------------------------
-- Mensajes: particionado mensual por created_at
-- ---------------------------------------------------------------------------
create table public.messages (
  id                bigint generated by default as identity,
  organization_id   bigint not null references public.organizations(id) on delete cascade,
  conversation_id   bigint not null references public.conversations(id) on delete cascade,
  direction         text not null check (direction in ('in', 'out')),
  sender_type       text not null check (sender_type in ('contact', 'bot', 'agent', 'campaign', 'flow', 'system')),
  sender_agent_id   bigint,
  ai_agent_id       bigint,
  type              text not null default 'text' check (type in
                      ('text', 'image', 'audio', 'video', 'document', 'sticker', 'location', 'interactive',
                       'contacts', 'template', 'product', 'unsupported')),
  text              text,
  media_path        text,                       -- ruta en Supabase Storage
  media_mime        text,
  media_filename    text,
  media_size        int,
  transcript        text,
  template_name     text,
  campaign_id       bigint,
  wa_message_id     text,
  status            text not null default 'received' check (status in
                      ('received', 'pending', 'sent', 'delivered', 'read', 'failed')),
  error_code        int,
  error             text,
  pricing_category  text,                       -- marketing | utility | authentication | service ...
  billable          boolean,
  metadata          jsonb,
  created_at        timestamptz not null default now(),
  updated_at        timestamptz not null default now(),
  primary key (id, created_at)
) partition by range (created_at);

