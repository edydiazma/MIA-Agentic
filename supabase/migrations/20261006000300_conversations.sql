create table public.typifications (
  id               bigint generated by default as identity primary key,
  organization_id  bigint not null references public.organizations(id) on delete cascade,
  name             text not null,
  criteria         text,                        -- cuándo aplicarla (guía a la IA)
  is_success       boolean not null default false,  -- cuenta como venta ganada
  is_active        boolean not null default true,
  position         int not null default 100,
  created_at       timestamptz not null default now(),
  unique (organization_id, name)
);

create table public.conversations (
  id                    bigint generated by default as identity primary key,
  organization_id       bigint not null references public.organizations(id) on delete cascade,
  contact_id            bigint not null references public.contacts(id) on delete cascade,
  channel_id            bigint not null references public.channels(id),
  ai_agent_id           bigint,                -- FK en 04
  status                text not null default 'bot' check (status in ('bot', 'human', 'closed')),
  assigned_agent_id     bigint references public.agents(id) on delete set null,
  group_id              bigint references public.groups(id) on delete set null,
  typification_id       bigint references public.typifications(id) on delete set null,
  -- Momentos clave (desnormalizados para SLA y listas; la historia completa está en conversation_events)
  handoff_reason        text,
  handoff_at            timestamptz,
  first_response_at     timestamptz,            -- primera respuesta de asesor después del handoff
  closed_at             timestamptz,
  reopened_count        int not null default 0,
  -- Contadores mantenidos por trigger desde messages
  message_count         int not null default 0,
  inbound_count         int not null default 0,
  unread_count          int not null default 0,
  last_message_at       timestamptz not null default now(),
  last_inbound_at       timestamptz,
  last_message_preview  text,
  -- Click to WhatsApp (referral de Meta)
  ad_source_type        text,
  ad_source_id          text,
  ad_headline           text,
  ad_source_url         text,
  ad_ctwa_clid          text,
  -- Clasificación por IA
  ai_summary            text,
  ai_sentiment          text check (ai_sentiment in ('positive', 'neutral', 'negative')),
  ai_typification_id    bigint references public.typifications(id) on delete set null,
  ai_classified_at      timestamptz,
  ai_inbound_mark       int not null default 0,  -- inbound_count en el último análisis
  created_at            timestamptz not null default now(),
  updated_at            timestamptz not null default now(),
  check (status <> 'closed' or closed_at is not null)
);
