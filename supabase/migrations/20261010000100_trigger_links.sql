alter table public.wa_links enable row level security;
alter table public.attribution_touches enable row level security;
alter table public.ad_entities enable row level security;
do $$
begin
  if exists (select 1 from pg_namespace where nspname = 'auth') then
    execute 'create policy org_read on public.wa_links for select to authenticated
             using (organization_id = private.current_org_id())';
    execute 'create policy org_read on public.attribution_touches for select to authenticated
             using (organization_id = private.current_org_id())';
    execute 'create policy org_read on public.ad_entities for select to authenticated
             using (organization_id = private.current_org_id())';
  end if;
end $$;
