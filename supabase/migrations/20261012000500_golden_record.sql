-- 23 · Registro maestro del cliente ("golden record") y llaves de identificación (docs/data-model.md §15)
--
-- golden_key_types: catálogo de llaves (sistema + propias de la empresa): teléfono, correo, usuario de red,
--   documento de identidad, nombres, apellidos, fecha de nacimiento, dirección, placa, VIN... con su normalizador,
--   si identifica a la persona (sirve para encontrar duplicados), si es dato sensible y si la IA debe extraerla.
-- contact_keys: cada valor capturado, con evidencia (mensaje, conversación, documento), fuente, confianza, rango
--   (principal / secundario) y vigencia. Se va llenando a medida que el chat recibe conversaciones y documentos.
-- contact_golden: el registro agregado por cliente (valores principales + listas), mantenido por trigger; no se
--   muestra en la ficha resumen, se consulta en "Datos maestros", en BI y para generar oportunidades.
-- contact_vehicles: vehículos del cliente (placa + VIN + marca/modelo/año) — base de oportunidades de taller,
--   retoma, seguros. key_extractions: auditoría de cada extracción de IA (conversación o documento).
-- contact_merge_candidates: clientes distintos que comparten una llave identificadora (posible duplicado).
-- =============================================================================

create table public.golden_key_types (
  id               bigint generated by default as identity primary key,
  organization_id  bigint references public.organizations(id) on delete cascade,   -- null = tipo del sistema
  key              text not null check (key ~ '^[a-z][a-z0-9_]{0,49}$'),
  label            text not null,
  normalizer       text not null check (normalizer in
                     ('phone', 'email', 'username', 'document', 'plate', 'vin', 'name', 'date', 'address', 'text')),
  is_identifier    boolean not null default false,   -- identifica a una sola persona (para encontrar duplicados)
  is_sensitive     boolean not null default false,   -- dato personal sensible: se enmascara a asesores
  multi            boolean not null default true,    -- admite varios valores (teléfonos, placas...)
  ai_extract       boolean not null default true,
  ai_hint          text,                             -- guía para la IA (formato, dónde suele aparecer)
  position         int not null default 100,
  archived_at      timestamptz,
  created_at       timestamptz not null default now()
);
create unique index golden_key_types_key_idx on public.golden_key_types (coalesce(organization_id, 0), key);

