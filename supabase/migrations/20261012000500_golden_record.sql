-- BI: completitud del registro maestro y cobertura por llave
create or replace view reporting.v_golden_coverage as
select g.organization_id, count(*) as contacts,
       round(avg(g.completeness_pct), 1) as avg_completeness,
       count(*) filter (where g.document_number is not null) as with_document,
       count(*) filter (where g.primary_email is not null) as with_email,
       count(*) filter (where g.birthdate is not null) as with_birthdate,
       count(*) filter (where jsonb_array_length(g.addresses) > 0) as with_address,
       count(*) filter (where cardinality(g.plates) > 0 or cardinality(g.vins) > 0) as with_vehicle,
       count(*) filter (where cardinality(g.phones) > 1) as with_secondary_phone
from public.contact_golden g group by g.organization_id;

