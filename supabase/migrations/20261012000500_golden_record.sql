create or replace function private.refresh_contact_golden(p_contact bigint) returns void
language plpgsql set search_path = public, pg_temp as $$
declare
  v_org bigint;
begin
  select organization_id into v_org from public.contacts where id = p_contact;
  if v_org is null then
    return;
  end if;
  insert into public.contact_golden as g (contact_id, organization_id, first_name, last_name, full_name, primary_phone,
      phones, primary_email, emails, usernames, document_type, document_number, birthdate, addresses, plates, vins,
      extra, completeness_pct, keys_count, updated_at)
  select p_contact, v_org,
    (array_agg(k.value order by (k.rank = 'primary') desc, k.confidence desc nulls last, k.last_seen_at desc)
       filter (where k.key_type = 'first_name'))[1],
    (array_agg(k.value order by (k.rank = 'primary') desc, k.confidence desc nulls last, k.last_seen_at desc)
       filter (where k.key_type = 'last_name'))[1],
    nullif(trim(concat_ws(' ',
      (array_agg(k.value order by (k.rank = 'primary') desc, k.last_seen_at desc) filter (where k.key_type = 'first_name'))[1],
      (array_agg(k.value order by (k.rank = 'primary') desc, k.last_seen_at desc) filter (where k.key_type = 'last_name'))[1])), ''),
    (array_agg(k.value_normalized order by (k.rank = 'primary') desc, k.verified desc, k.last_seen_at desc)
       filter (where k.key_type = 'phone'))[1],
    coalesce(array_agg(distinct k.value_normalized) filter (where k.key_type = 'phone'), '{}'),
    (array_agg(k.value_normalized order by (k.rank = 'primary') desc, k.verified desc, k.last_seen_at desc)
       filter (where k.key_type = 'email'))[1],
    coalesce(array_agg(distinct k.value_normalized) filter (where k.key_type = 'email'), '{}'),
    coalesce(jsonb_agg(distinct jsonb_build_object('network', k.subtype, 'username', k.value_normalized))
       filter (where k.key_type = 'username'), '[]'),
    (array_agg(k.subtype order by (k.rank = 'primary') desc, k.verified desc, k.last_seen_at desc)
       filter (where k.key_type = 'document'))[1],
    (array_agg(k.value_normalized order by (k.rank = 'primary') desc, k.verified desc, k.last_seen_at desc)
       filter (where k.key_type = 'document'))[1],
    (array_agg(k.value_normalized order by (k.rank = 'primary') desc, k.confidence desc nulls last)
       filter (where k.key_type = 'birthdate' and k.value_normalized ~ '^\d{4}-\d{2}-\d{2}$'))[1]::date,
    coalesce(jsonb_agg(distinct jsonb_build_object('type', k.subtype, 'value', k.value) || k.data)
       filter (where k.key_type = 'address'), '[]'),
    coalesce(array_agg(distinct k.value_normalized) filter (where k.key_type = 'plate'), '{}'),
    coalesce(array_agg(distinct k.value_normalized) filter (where k.key_type = 'vin'), '{}'),
    coalesce((select jsonb_object_agg(x.key_type, x.vals) from (
        select k2.key_type, jsonb_agg(distinct k2.value) as vals from public.contact_keys k2
        where k2.contact_id = p_contact and k2.status = 'active' and k2.key_type not in
          ('phone', 'email', 'username', 'document', 'first_name', 'last_name', 'birthdate', 'address', 'plate', 'vin')
        group by k2.key_type) x), '{}'),
    -- completitud: nombres, apellidos, teléfono, correo, documento, fecha de nacimiento, dirección (7 llaves base)
    (100 * (
      (count(*) filter (where k.key_type = 'first_name') > 0)::int +
      (count(*) filter (where k.key_type = 'last_name') > 0)::int +
      (count(*) filter (where k.key_type = 'phone') > 0)::int +
      (count(*) filter (where k.key_type = 'email') > 0)::int +
      (count(*) filter (where k.key_type = 'document') > 0)::int +
      (count(*) filter (where k.key_type = 'birthdate') > 0)::int +
      (count(*) filter (where k.key_type = 'address') > 0)::int) / 7)::smallint,
    count(*), now()
  from public.contact_keys k
  where k.contact_id = p_contact and k.status = 'active'
  on conflict (contact_id) do update set
    first_name = excluded.first_name, last_name = excluded.last_name, full_name = excluded.full_name,
    primary_phone = excluded.primary_phone, phones = excluded.phones, primary_email = excluded.primary_email,
    emails = excluded.emails, usernames = excluded.usernames, document_type = excluded.document_type,
    document_number = excluded.document_number, birthdate = excluded.birthdate, addresses = excluded.addresses,
    plates = excluded.plates, vins = excluded.vins, extra = excluded.extra, completeness_pct = excluded.completeness_pct,
    keys_count = excluded.keys_count, updated_at = now();
end $$;
revoke all on function private.refresh_contact_golden(bigint) from public;

create or replace function private.trg_contact_keys_golden() returns trigger
language plpgsql set search_path = public, pg_temp as $$
begin
  perform private.refresh_contact_golden(coalesce(new.contact_id, old.contact_id));
  if tg_op = 'UPDATE' and new.contact_id is distinct from old.contact_id then
    perform private.refresh_contact_golden(old.contact_id);
  end if;
  return null;
end $$;
revoke all on function private.trg_contact_keys_golden() from public;
create trigger trg_contact_keys_golden after insert or update or delete on public.contact_keys
  for each row execute function private.trg_contact_keys_golden();

-- Datos del canal → llaves (teléfono y @usuario de WhatsApp verificados por el canal; correo escrito en la ficha)
create or replace function private.trg_contacts_golden_keys() returns trigger
language plpgsql set search_path = public, pg_temp as $$
begin
  if new.wa_id is not null and (tg_op = 'INSERT' or new.wa_id is distinct from old.wa_id) then
    insert into public.contact_keys (organization_id, contact_id, key_type, subtype, value, value_normalized, rank,
                                     verified, confidence, source)
    values (new.organization_id, new.id, 'phone', 'whatsapp', new.wa_id, new.wa_id,
            case when exists (select 1 from public.contact_keys where contact_id = new.id and key_type = 'phone'
                              and coalesce(subtype, '') = 'whatsapp' and rank = 'primary' and status = 'active')
                 then 'secondary' else 'primary' end, true, 1, 'whatsapp')
    on conflict (contact_id, key_type, coalesce(subtype, ''), value_normalized)
      do update set verified = true, last_seen_at = now(), seen_count = public.contact_keys.seen_count + 1;
  end if;
  if new.wa_username is not null and (tg_op = 'INSERT' or new.wa_username is distinct from old.wa_username) then
    insert into public.contact_keys (organization_id, contact_id, key_type, subtype, value, value_normalized, rank,
                                     verified, confidence, source)
    values (new.organization_id, new.id, 'username', 'whatsapp', new.wa_username, lower(new.wa_username), 'secondary',
            true, 1, 'whatsapp')
    on conflict (contact_id, key_type, coalesce(subtype, ''), value_normalized) do update set last_seen_at = now();
  end if;
  if new.email is not null and (tg_op = 'INSERT' or new.email is distinct from old.email) then
    insert into public.contact_keys (organization_id, contact_id, key_type, value, value_normalized, rank, confidence,
                                     source)
    values (new.organization_id, new.id, 'email', new.email, lower(new.email), 'secondary', 0.9, 'agent')
    on conflict (contact_id, key_type, coalesce(subtype, ''), value_normalized) do update set last_seen_at = now();
  end if;
  return null;
end $$;
revoke all on function private.trg_contacts_golden_keys() from public;
create trigger trg_contacts_golden_keys after insert or update of wa_id, wa_username, email on public.contacts
  for each row execute function private.trg_contacts_golden_keys();

