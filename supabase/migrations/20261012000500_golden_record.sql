create table public.contact_keys (
  id                bigint generated by default as identity primary key,
  organization_id   bigint not null references public.organizations(id) on delete cascade,
  contact_id        bigint not null references public.contacts(id) on delete cascade,
  key_type          text not null,                  -- golden_key_types.key
  subtype           text,                           -- documento: CC/NIT/PAS…; usuario: instagram/facebook…;
                                                    -- dirección: casa/trabajo/envío; teléfono: móvil/fijo
  value             text not null,                  -- como se capturó
  value_normalized  text not null,                  -- para buscar y cruzar (E.164, minúsculas, placa sin guiones…)
  data              jsonb not null default '{}'::jsonb,   -- dirección estructurada (ciudad, país, geo), etc.
  rank              text not null default 'secondary' check (rank in ('primary', 'secondary')),
  status            text not null default 'active' check (status in ('active', 'superseded', 'rejected')),
  verified          boolean not null default false, -- confirmado por un asesor o por el canal (ej. teléfono de WhatsApp)
  confidence        real check (confidence between 0 and 1),
  source            text not null check (source in
                      ('whatsapp', 'channel', 'ai_conversation', 'ai_document', 'agent', 'import', 'api', 'crm', 'flow', 'form')),
  conversation_id   bigint references public.conversations(id) on delete set null,
  message_id        bigint,                         -- messages es particionada: sin FK
  extraction_id     bigint,                         -- key_extractions.id
  evidence          text,                           -- fragmento del texto o del documento
  seen_count        int not null default 1,
  first_seen_at     timestamptz not null default now(),
  last_seen_at      timestamptz not null default now(),
  created_by        bigint references public.agents(id) on delete set null,
  updated_at        timestamptz not null default now()
);
create unique index contact_keys_value_idx on public.contact_keys
  (contact_id, key_type, coalesce(subtype, ''), value_normalized);
-- Cruce entre clientes: ¿quién más tiene esta placa / documento / correo?
create index contact_keys_lookup_idx on public.contact_keys (organization_id, key_type, value_normalized)
  where status = 'active';
create index contact_keys_contact_idx on public.contact_keys (contact_id, key_type, rank);
-- A lo sumo un valor principal activo por cliente, tipo y subtipo
create unique index contact_keys_primary_idx on public.contact_keys (contact_id, key_type, coalesce(subtype, ''))
  where rank = 'primary' and status = 'active';
create trigger trg_contact_keys_updated before update on public.contact_keys
  for each row execute function public.set_updated_at();

