create table public.contact_consents (
  id               bigint generated by default as identity primary key,
  organization_id  bigint not null references public.organizations(id) on delete cascade,
  contact_id       bigint not null references public.contacts(id) on delete cascade,
  consent_type     text not null,               -- habeas_data, terms, marketing, data_sharing, call_recording…
  granted          boolean not null,
  policy_version   text,                        -- versión del texto aceptado
  channel_id       bigint references public.channels(id) on delete set null,
  conversation_id  bigint references public.conversations(id) on delete set null,
  message_id       bigint,                      -- respuesta del cliente (evidencia)
  evidence         text,                        -- texto mostrado / respuesta
  source           text not null check (source in ('whatsapp', 'flow', 'agent', 'form', 'import', 'api', 'ai')),
  recorded_by      bigint references public.agents(id) on delete set null,
  recorded_at      timestamptz not null default now(),
  revoked_at       timestamptz
);
create index contact_consents_contact_idx on public.contact_consents (contact_id, consent_type, recorded_at desc);
create index contact_consents_org_idx on public.contact_consents (organization_id, consent_type, granted);
