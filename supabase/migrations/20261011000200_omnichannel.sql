-- Reporting por canal ---------------------------------------------------------------------------------
create table reporting.daily_channels (
  organization_id  bigint not null,
  day              date not null,
  channel_id       bigint not null,
  provider         text not null,
  conversations    int not null default 0,   -- conversaciones creadas
  inbound          int not null default 0,
  outbound         int not null default 0,
  contacts_new     int not null default 0,
  refreshed_at     timestamptz not null default now(),
  primary key (organization_id, day, channel_id)
);

create or replace function reporting.refresh_channels(p_org bigint, p_from date, p_to date) returns void
language plpgsql set search_path = reporting, public, pg_temp as $$
declare
  tz  text := (select timezone from public.organizations where id = p_org);
  lo  timestamptz := (p_from::timestamp at time zone tz);
  hi  timestamptz := ((p_to + 1)::timestamp at time zone tz);
begin
  delete from reporting.daily_channels where organization_id = p_org and day between p_from and p_to;
  insert into reporting.daily_channels (organization_id, day, channel_id, provider, conversations, inbound, outbound,
      contacts_new)
  select p_org, x.day, x.channel_id, ch.provider, sum(x.conversations), sum(x.inbound), sum(x.outbound),
         sum(x.contacts_new)
  from (
    select (c.created_at at time zone tz)::date as day, c.channel_id, count(*) as conversations, 0 as inbound,
           0 as outbound, 0 as contacts_new
    from public.conversations c
    where c.organization_id = p_org and c.created_at >= lo and c.created_at < hi
    group by 1, 2
    union all
    select (m.created_at at time zone tz)::date, c.channel_id, 0, count(*) filter (where m.direction = 'in'),
           count(*) filter (where m.direction = 'out'), 0
    from public.messages m join public.conversations c on c.id = m.conversation_id
    where m.organization_id = p_org and m.created_at >= lo and m.created_at < hi
    group by 1, 2
    union all
    -- contacto nuevo: se cuenta en el canal de su primera conversación
    select (k.created_at at time zone tz)::date, f.channel_id, 0, 0, 0, count(*)
    from public.contacts k
    cross join lateral (select c.channel_id from public.conversations c where c.contact_id = k.id
                        order by c.created_at limit 1) f
    where k.organization_id = p_org and k.created_at >= lo and k.created_at < hi
    group by 1, 2
  ) x
  join public.channels ch on ch.id = x.channel_id
  group by 2, 3, 4;
end $$;
revoke all on function reporting.refresh_channels(bigint, date, date) from public;

