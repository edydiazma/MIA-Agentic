-- Reporting
create table reporting.daily_journeys (
  organization_id  bigint not null,
  day              date not null,
  journey_id       bigint not null,
  step_id          text not null,
  variant          text not null default '',
  entered          int not null default 0,
  sent             int not null default 0,
  delivered        int not null default 0,
  read             int not null default 0,
  replied          int not null default 0,
  clicked          int not null default 0,
  failed           int not null default 0,
  goal_met         int not null default 0,
  exited           int not null default 0,
  refreshed_at     timestamptz not null default now(),
  primary key (organization_id, day, journey_id, step_id, variant)
);

create or replace function reporting.refresh_journeys(p_org bigint, p_from date, p_to date) returns void
language plpgsql set search_path = reporting, public, pg_temp as $$
declare
  tz  text := (select timezone from public.organizations where id = p_org);
  lo  timestamptz := (p_from::timestamp at time zone tz);
  hi  timestamptz := ((p_to + 1)::timestamp at time zone tz);
begin
  delete from reporting.daily_journeys where organization_id = p_org and day between p_from and p_to;
  insert into reporting.daily_journeys (organization_id, day, journey_id, step_id, variant, entered, sent, delivered,
      read, replied, clicked, failed, goal_met, exited)
  select p_org, (e.created_at at time zone tz)::date, e.journey_id, e.step_id, coalesce(e.variant, ''),
         count(*) filter (where e.kind = 'entered'), count(*) filter (where e.kind = 'sent'),
         count(*) filter (where e.kind = 'delivered'), count(*) filter (where e.kind = 'read'),
         count(*) filter (where e.kind = 'replied'), count(*) filter (where e.kind = 'clicked'),
         count(*) filter (where e.kind = 'failed'), count(*) filter (where e.kind = 'goal_met'),
         count(*) filter (where e.kind = 'exited')
  from public.journey_events e
  where e.organization_id = p_org and e.created_at >= lo and e.created_at < hi
  group by 2, 3, 4, 5;
end $$;
revoke all on function reporting.refresh_journeys(bigint, date, date) from public;

create or replace function reporting.refresh_range(p_org bigint, p_from date, p_to date) returns void
language plpgsql set search_path = reporting, public, pg_temp as $$
begin
  perform reporting.refresh_core(p_org, p_from, p_to);
  perform reporting.refresh_flows(p_org, p_from, p_to);
  perform reporting.refresh_links(p_org, p_from, p_to);
  perform reporting.refresh_channels(p_org, p_from, p_to);
  perform reporting.refresh_qa(p_org, p_from, p_to);
  perform reporting.refresh_api(p_org, p_from, p_to);
  perform reporting.refresh_products(p_org, p_from, p_to);
  perform reporting.refresh_ads(p_org, p_from, p_to);
  perform reporting.refresh_service(p_org, p_from, p_to);
  perform reporting.refresh_copilot(p_org, p_from, p_to);
  perform reporting.refresh_journeys(p_org, p_from, p_to);
end $$;

