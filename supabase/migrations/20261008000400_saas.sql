do $guard$
begin
  if not exists (select 1 from pg_namespace where nspname = 'auth') then
    return;
  end if;
  -- Varias empresas por usuario: la empresa activa viaja en el JWT (app_metadata.org_id)
  execute $f$
    create or replace function private.current_org_id() returns bigint
    language sql stable security definer set search_path = public, pg_temp as $$
      select coalesce(
        (select organization_id from public.agents
          where auth_user_id = auth.uid() and is_active
            and organization_id = nullif(auth.jwt() -> 'app_metadata' ->> 'org_id', '')::bigint),
        (select organization_id from public.agents where auth_user_id = auth.uid() and is_active
          order by organization_id limit 1))
    $$;
  $f$;
  execute $p$
    create policy org_read on public.tracking_sites for select to authenticated using (organization_id = private.current_org_id());
    create policy org_read on public.attributions for select to authenticated using (organization_id = private.current_org_id());
    create policy org_read on public.conversion_actions for select to authenticated using (organization_id = private.current_org_id());
    create policy org_read on public.conversion_events for select to authenticated using (organization_id = private.current_org_id());
    create policy org_read on public.deals for select to authenticated using (organization_id = private.current_org_id());
    create policy org_read on public.voice_agents for select to authenticated using (organization_id = private.current_org_id());
    create policy org_read on public.calls for select to authenticated using (organization_id = private.current_org_id());
    create policy org_read on public.call_turns for select to authenticated
      using (exists (select 1 from public.calls c where c.id = call_id and c.organization_id = private.current_org_id()));
    create policy org_read on public.usage_counters for select to authenticated using (organization_id = private.current_org_id());
    create policy org_read on public.subscriptions for select to authenticated using (organization_id = private.current_org_id());
    create policy public_read on public.plans for select to authenticated using (is_public);
  $p$;
end $guard$;
