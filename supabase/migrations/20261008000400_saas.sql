-- ---------------------------------------------------------------------------
-- Consumo: contadores mensuales por métrica (solo eventos de baja frecuencia que se limitan en tiempo real).
-- Mensajes y costo de IA se leen de reporting.* (sin contención en filas calientes).
-- ---------------------------------------------------------------------------
create table public.usage_counters (
  organization_id  bigint not null references public.organizations(id) on delete cascade,
  period           date not null,                 -- primer día del mes (UTC)
  metric           text not null check (metric in ('conversations', 'voice_minutes', 'campaign_recipients')),
  value            numeric not null default 0,
  updated_at       timestamptz not null default now(),
  primary key (organization_id, period, metric)
);

create or replace function public.bump_usage(p_org bigint, p_metric text, p_delta numeric) returns void
language sql set search_path = public, pg_temp as $$
  insert into public.usage_counters (organization_id, period, metric, value)
  values (p_org, date_trunc('month', now() at time zone 'UTC')::date, p_metric, p_delta)
  on conflict (organization_id, period, metric)
  do update set value = public.usage_counters.value + excluded.value, updated_at = now();
$$;

create or replace function public.trg_usage_conversations() returns trigger
language plpgsql set search_path = public, pg_temp as $$
begin
  perform public.bump_usage(new.organization_id, 'conversations', 1);
  return null;
end $$;
create trigger trg_conversations_usage after insert on public.conversations
  for each row execute function public.trg_usage_conversations();

create or replace function public.trg_usage_calls() returns trigger
language plpgsql set search_path = public, pg_temp as $$
begin
  if new.duration_s is not null and old.duration_s is null and new.duration_s > 0 then
    perform public.bump_usage(new.organization_id, 'voice_minutes', ceil(new.duration_s / 60.0));
  end if;
  return null;
end $$;
create trigger trg_calls_usage after update of ended_at on public.calls
  for each row execute function public.trg_usage_calls();

create or replace function public.trg_usage_campaign_recipients() returns trigger
language plpgsql set search_path = public, pg_temp as $$
declare org bigint;
begin
  if new.status = 'sent' and old.status is distinct from 'sent' then
    select organization_id into org from public.campaigns where id = new.campaign_id;
    perform public.bump_usage(org, 'campaign_recipients', 1);
  end if;
  return null;
end $$;
create trigger trg_campaign_recipients_usage after update of status on public.campaign_recipients
  for each row execute function public.trg_usage_campaign_recipients();

-- Límite del plan: devuelve {allowed, limit, used}. Métricas de conteo (channels, users...) se calculan en vivo.
create or replace function public.check_limit(p_org bigint, p_metric text) returns jsonb
language plpgsql stable set search_path = public, pg_temp as $$
declare
  lim numeric;
  used numeric;
  v_period date := date_trunc('month', now() at time zone 'UTC')::date;
begin
  select (p.limits ->> p_metric)::numeric into lim
  from public.organizations o join public.plans p on p.id = o.plan_id where o.id = p_org;
  used := case p_metric
    when 'channels' then (select count(*) from public.channels where organization_id = p_org)
    when 'users' then (select count(*) from public.agents where organization_id = p_org and is_active)
    when 'ai_agents' then (select count(*) from public.ai_agents where organization_id = p_org)
    when 'flows' then (select count(*) from public.flows where organization_id = p_org and status <> 'archived')
    when 'conversations_month' then coalesce((select value from public.usage_counters
                               where organization_id = p_org and period = v_period and metric = 'conversations'), 0)
    when 'voice_minutes_month' then coalesce((select value from public.usage_counters
                               where organization_id = p_org and period = v_period and metric = 'voice_minutes'), 0)
    when 'campaign_recipients_month' then coalesce((select value from public.usage_counters
                               where organization_id = p_org and period = v_period and metric = 'campaign_recipients'), 0)
    else 0 end;
  return jsonb_build_object('metric', p_metric, 'limit', lim, 'used', used, 'allowed', lim is null or used < lim);
end $$;

