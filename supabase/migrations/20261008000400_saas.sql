-- Seguridad: funciones internas fuera de la API pública
revoke execute on function public.bump_usage(bigint, text, numeric), public.trg_usage_conversations(),
  public.trg_usage_calls(), public.trg_usage_campaign_recipients(), public.check_limit(bigint, text) from public;
do $$ begin
  if exists (select 1 from pg_roles where rolname = 'anon') then
    revoke execute on function public.bump_usage(bigint, text, numeric), public.trg_usage_conversations(),
      public.trg_usage_calls(), public.trg_usage_campaign_recipients(), public.check_limit(bigint, text)
      from anon, authenticated;
  end if;
end $$;

